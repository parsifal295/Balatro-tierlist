const tidy = (value: string) =>
  value
    .replace(/\s+,/g, ",")
    .replace(/\s+\./g, ".")
    .replace(/\s{2,}/g, " ")
    .trim();

export const normalizeEffectText = (effect: string | undefined) =>
  (effect ?? "").replace(/^효과 원문:\s*/u, "").trim();

export function translateEffect(effect: string | undefined) {
  const normalized = normalizeEffectText(effect);

  if (normalized.length === 0) {
    return "";
  }

  const exactTranslation = exactTranslations[normalized];

  if (exactTranslation) {
    return exactTranslation;
  }

  const translated = replacements.reduce(
    (current, [pattern, replacement]) => current.replace(pattern, replacement),
    normalized
  );

  const cleaned = tidy(translated);

  if (/[가-힣]/.test(cleaned)) {
    return cleaned;
  }

  return `번역 준비 필요: ${cleaned}`;
}
